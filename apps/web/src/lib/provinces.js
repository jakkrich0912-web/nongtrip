// ชื่อจังหวัดตามภาษาที่เลือก ไม่รู้จักชื่อ (เช่นข้อมูลเก่า) คืนชื่อเดิม
export const provinceLabel = (name, lang = 'th') => (lang === 'en' && PROVINCE_EN[name]) || name;
export const regionLabel = (region, lang = 'th') => (lang === 'en' ? `${REGION_EN[region] ?? region} region` : `ภาค${region}`);

// ค้นจังหวัดได้ทั้งชื่อไทยและอังกฤษ ไม่สนตัวพิมพ์และช่องว่าง
export function matchProvince(name, query) {
  const q = (query ?? '').trim().toLowerCase().replace(/\s+/g, '');
  if (!q) return true;
  return name.includes(q) || (PROVINCE_EN[name] ?? '').toLowerCase().replace(/\s+/g, '').includes(q);
}
